# /// script
# requires-python = ">=3.11"
# dependencies = ["fonttools[woff]==4.68.0"]
# ///
"""uv run scripts/subset-maple.py --source-dir .qa/font-source

Run npm run build first. Sources are the unmodified official v7.9 variable
WOFF2 and MapleMono-CN-unhinted.zip (see public/fonts/README.md).
Only the static site's non-Latin glyphs are subset; unknown glyphs still have
system fallbacks, and the browser regression checks catch stale coverage.
"""
import argparse
import hashlib
import json
import re
import zipfile
from html.parser import HTMLParser
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source-dir", type=Path, required=True)
args = parser.parse_args()
sources = args.source_dir
out = ROOT / "public/fonts"
out.mkdir(parents=True, exist_ok=True)


class Text(HTMLParser):
    def __init__(self):
        super().__init__()
        self.skip = 0
        self.chars = set()

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self.skip += 1

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self.skip -= 1

    def handle_data(self, data):
        if not self.skip:
            self.chars.update(map(ord, data))


text = Text()
for file in ["index.html", "404.html", *[f"resume/{lang}/index.html" for lang in ("en", "zh", "en-1p", "zh-1p")]]:
    text.feed((ROOT / "dist" / file).read_text())

latin_path = sources / "MapleMono-Variable.woff2"
assert hashlib.sha256(latin_path.read_bytes()).hexdigest() == "e7080ef37fa8b3a38f71446e53e546634c27ce2cfe97673478cafc029d6344ee"
latin = TTFont(latin_path)
assert latin["name"].getDebugName(5) == "Version 7.900"
latin_points = set(latin.getBestCmap())
# The one-page company/role separator is generated by CSS, not an HTML node.
text.chars.add(0xFF5C)
cjk_points = text.chars - latin_points - {9, 10, 13}
archive = sources / "MapleMono-CN-unhinted.zip"
assert hashlib.sha256(archive.read_bytes()).hexdigest() == "d41cb72721e99cfe4fbd1a7b0f182a013457de46aa612018f924dd024699d3b9"
(out / "maple-latin.woff2").write_bytes(latin_path.read_bytes())

files = []
# English pages need just the language switch (and the paper role separator),
# not the Chinese résumé's entire vocabulary.
ui_points = cjk_points & set(map(ord, "中文版本首页简历张帅｜"))
groups = {"ui": ui_points, "text": cjk_points - ui_points}
css = "/* Generated by scripts/subset-maple.py; do not edit. */\n"
with zipfile.ZipFile(archive) as z:
    (out / "OFL-Maple.txt").write_bytes(z.read("LICENSE.txt"))
    for weight, name in [(400, "Regular"), (500, "Medium"), (600, "SemiBold"), (700, "Bold")]:
        font = TTFont(z.open(f"MapleMono-CN-{name}.ttf"))
        assert font["OS/2"].usWeightClass == weight
        missing = cjk_points - set(font.getBestCmap())
        assert not missing, f"Missing source glyphs: {missing}"
        for group, points in groups.items():
            font = TTFont(z.open(f"MapleMono-CN-{name}.ttf"), recalcTimestamp=False)
            options = subset.Options()
            options.name_IDs = ["*"]
            options.name_legacy = True
            options.name_languages = ["*"]
            sub = subset.Subsetter(options=options)
            sub.populate(unicodes=points)
            sub.subset(font)
            font.flavor = "woff2"
            file = f"maple-cn-{group}-{weight}.woff2"
            font.save(out / file)
            files.append(file)
            ranges = ",".join(f"U+{point:X}" for point in sorted(points))
            css += f"""@font-face {{
  font-family: 'Maple Mono CN';
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  src: url('/fonts/{file}') format('woff2');
  unicode-range: {ranges};
}}
"""

# A separate family prevents the CN file's static weight matching from
# overriding the variable Latin face. Latin stays one request on English pages.
(ROOT / "src/styles/maple-cn.css").write_text(css)
files += ["maple-latin.woff2", "geist-latin.woff2", "geist-mono-latin.woff2"]
manifest = {
    "mapleVersion": "7.900", "fontToolsVersion": "4.68.0",
    "latinCodepoints": sorted(latin_points), "cjkCodepoints": sorted(cjk_points),
    "uiCodepoints": sorted(ui_points),
    "files": {name: {"bytes": (out / name).stat().st_size, "sha256": hashlib.sha256((out / name).read_bytes()).hexdigest()} for name in files},
}
serialized = json.dumps(manifest, ensure_ascii=False, indent=2)
serialized = re.sub(r'("\w+Codepoints": )\[([\d,\s]+)\]', lambda match: match[1] + '[' + ''.join(match[2].split()) + ']', serialized)
(out / "manifest.json").write_text(serialized + "\n")
print(f"Latin: {len(latin_points)} codepoints; CN: {len(cjk_points)} codepoints × 4 real weights")
print({name: info["bytes"] for name, info in manifest["files"].items()})
